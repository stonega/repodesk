import { writeFile } from "node:fs/promises";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import type { RepositoryManager } from "../src/upstream/codegraph/repository-manager.ts";
import type { CodeGraphRunner } from "../src/upstream/codegraph/runner.ts";
import { createCodeTruthMcpServer } from "../src/upstream/http/mcp-server.ts";

// Listing definitions must never inspect a repository or contact an upstream API.
const unused = new Proxy(
  {},
  {
    get() {
      throw new Error("Tool catalog generation attempted repository access");
    },
  },
);
const server = createCodeTruthMcpServer({
  repositories: unused as RepositoryManager,
  codegraph: unused as CodeGraphRunner,
});
const client = new Client({ name: "tool-catalog", version: "1" });
const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
try {
  await server.connect(serverTransport);
  await client.connect(clientTransport);
  const { tools } = await client.listTools();
  const catalog = tools.map(({ name, title, description, inputSchema }) => ({
    name,
    title: title ?? name,
    description: description ?? name,
    inputSchema,
  }));
  const file = new URL("../src/tool-catalog.ts", import.meta.url);
  await writeFile(
    file,
    `// Generated by scripts/update-tool-catalog.ts. Do not edit manually.\nexport const codeTruthToolCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`,
  );
} finally {
  await client.close();
  await server.close();
}
